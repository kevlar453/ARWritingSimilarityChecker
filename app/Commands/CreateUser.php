<?php

namespace App\Commands;

use App\Models\UserModel;
use CodeIgniter\CLI\BaseCommand;
use CodeIgniter\CLI\CLI;

class CreateUser extends BaseCommand
{
    protected $group       = 'User';
    protected $name        = 'user:create';
    protected $description = 'Membuat akun pengguna baru secara langsung melalui CLI';
    protected $usage       = 'user:create [options]';
    protected $arguments   = [];
    protected $options     = [
        '--email'       => 'Alamat email pengguna (wajib)',
        '--name'        => 'Nama pengguna (opsional, default: nama dari email)',
        '--password'    => 'Kata sandi akun (opsional, jika kosong akan digenerate otomatis)',
        '--role'        => 'Peran pengguna: user / admin (default: user)',
        '--status'      => 'Status akun: active / pending_verification / inactive (default: active)',
        '--institution' => 'Nama institusi (opsional, default: Institusi Akademik)',
    ];

    public function run(array $params)
    {
        CLI::write("=== Pembuatan Akun Pengguna AR Tilik ===", 'green');

        $email = trim((string) (CLI::getOption('email') ?? ''));
        if (empty($email)) {
            $email = trim((string) CLI::prompt('Masukkan alamat email'));
        }

        if (empty($email) || ! filter_var($email, FILTER_VALIDATE_EMAIL)) {
            CLI::error("❌ Alamat email tidak valid: {$email}");
            return;
        }

        $userModel = new UserModel();
        $existing = $userModel->where('email', $email)->first();
        if ($existing) {
            CLI::error("❌ Email '{$email}' sudah terdaftar (User ID: {$existing['id']}).");
            return;
        }

        $name = trim((string) (CLI::getOption('name') ?? ''));
        if (empty($name)) {
            $parts = explode('@', $email);
            $name = ucfirst($parts[0]);
        }

        $password = (string) (CLI::getOption('password') ?? '');
        $autoGenerated = false;
        if (empty($password)) {
            // Generate kata sandi aman otomatis 16 karakter
            $chars = 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789!@#$%*';
            $password = '';
            for ($i = 0; $i < 16; $i++) {
                $password .= $chars[random_int(0, strlen($chars) - 1)];
            }
            $autoGenerated = true;
        }

        $role = strtolower(trim((string) (CLI::getOption('role') ?? 'user')));
        if (! in_array($role, ['user', 'admin'], true)) {
            CLI::error("❌ Role harus 'user' atau 'admin'. Diberikan: {$role}");
            return;
        }

        $status = strtolower(trim((string) (CLI::getOption('status') ?? 'active')));
        if (! in_array($status, ['active', 'pending_verification', 'inactive'], true)) {
            CLI::error("❌ Status harus 'active', 'pending_verification', atau 'inactive'. Diberikan: {$status}");
            return;
        }

        $institution = trim((string) (CLI::getOption('institution') ?? 'Institusi Akademik'));

        $now = date('Y-m-d H:i:s');
        $resetAt = date('Y-m-d 00:00:00', strtotime('next monday'));

        $userData = [
            'name'                            => $name,
            'email'                           => $email,
            'password_hash'                   => password_hash($password, PASSWORD_DEFAULT),
            'institution'                     => $institution,
            'role'                            => $role,
            'subscription_tier'               => 'free',
            'subscription_expires_at'         => null,
            'status'                          => $status,
            'verification_token'              => null,
            'verification_token_expires_at'   => null,
            'email_verified_at'               => ($status === 'active') ? $now : null,
            'reset_password_token'            => null,
            'reset_password_expires_at'       => null,
            'free_submissions_used_this_week' => 0,
            'week_reset_at'                   => $resetAt,
            'bonus_submissions'               => 0,
            'referred_by_code'                => null,
            'uploaded_corpus_count'           => 0,
            'last_login_at'                   => null,
            'created_at'                      => $now,
            'updated_at'                      => $now,
        ];

        $userId = $userModel->insert($userData);

        if (! $userId) {
            CLI::error("❌ Gagal menyimpan data pengguna ke database.");
            return;
        }

        CLI::write("✓ Akun berhasil dibuat!", 'green');
        CLI::table([
            ['ID', $userId],
            ['Nama', $name],
            ['Email', $email],
            ['Kata Sandi', $password],
            ['Role', $role],
            ['Status', $status],
            ['Email Verified At', ($status === 'active') ? $now : '-'],
            ['Institusi', $institution],
            ['Password Tergenerate', $autoGenerated ? 'Ya (Otomatis)' : 'Manual'],
        ], ['Field', 'Nilai']);
    }
}
